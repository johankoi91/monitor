// Runs only against the isolated Go browser fixture, never a business host.
const assert = require('node:assert/strict');
const { openPage, openSection, checkCurrent } = require('./navigation.cjs');
const containerLoading = require('./container-loading.cjs');
const { chromium } = require(process.env.AVOPS_PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  assert.equal(process.env.AVOPS_ISOLATED_UI_TEST, '1');
  const url = new URL(process.env.AVOPS_UI_URL);
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname));
  const browser = await chromium.launch({ headless: true, executablePath: process.env.AVOPS_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  let page;
  try {
    page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => requests.push(new URL(r.url()).pathname));
    url.searchParams.set('view','status');
    await page.goto(url.toString());
    await page.getByLabel('账号', {exact:true}).fill('fixture');
    await page.getByLabel('密码', {exact:true}).fill('fixture123');
    await page.getByRole('button', {name:'登录',exact:true}).click();
    await page.getByRole('heading', {name:'容器服务',exact:true}).waitFor();
    assert.ok(!requests.includes('/api/v1/containers') && !requests.includes('/api/v1/notifications/status'));
    await openPage(page, '监控', '部署服务容器发现');
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('button',{name:'详情',exact:true}).click();
    const detailDialog=page.getByRole('dialog');
    await detailDialog.getByRole('heading',{name:'容器信息',exact:true}).waitFor();
    await detailDialog.getByRole('heading',{name:'启动配置',exact:true}).waitFor();
    await detailDialog.getByText('查看原始数据',{exact:true}).click();
    assert.ok((await detailDialog.locator('pre').innerText()).includes('agora_local_ap'));
    await detailDialog.locator('.ant-modal-close').click();
    await detailDialog.waitFor({state:'hidden'});
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('checkbox').check();
    const keyword = page.getByLabel('容器名关键词', {exact:true});
    await keyword.fill(' UNUSED- ');
    const filtered = page.waitForResponse(r => {
      const request = new URL(r.url());
      return request.pathname === '/api/v1/containers' && request.searchParams.get('name') === 'UNUSED-' && r.ok();
    });
    await page.getByRole('button', {name:'筛选',exact:true}).click();
    const filteredRows = await (await filtered).json();
    assert.equal(filteredRows.page, 1);
    assert.equal(filteredRows.total, 54);
    assert.ok(filteredRows.containers.every(c => c.container_name.includes('unused-')));
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).waitFor({state:'hidden'});
    assert.ok((await page.locator('.inventory-selection-bar').innerText()).includes('1'));
    await keyword.fill('');
    const restored = page.waitForResponse(r => {
      const request = new URL(r.url());
      return request.pathname === '/api/v1/containers' && request.searchParams.get('name') === '' && r.ok();
    });
    await keyword.press('Enter');
    await restored;
    assert.equal(await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('checkbox').isChecked(), true);
    await page.getByRole('button',{name:'设置纳管规则',exact:true}).click();
    await page.getByRole('dialog',{name:'设置纳管规则',exact:true}).waitFor();
    await page.getByLabel('分组名', {exact:true}).fill('回归验证组');
    await page.getByRole('button', {name:'加入待保存变更',exact:true}).click();
    await page.getByRole('dialog',{name:'设置纳管规则',exact:true}).waitFor({state:'hidden'});
    await openPage(page, '监控', '容器服务');
    assert.ok((await page.locator('.inventory-workbench').innerText()).includes('回归验证组'));
    await openPage(page, '监控', '部署服务容器发现');
    const inventoryToggle = page.getByRole('navigation',{name:'工作台导航'}).getByRole('button',{name:'监控',exact:true});
    await inventoryToggle.focus(); await inventoryToggle.press('Enter');
    assert.equal(await inventoryToggle.getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator('.workspace-page-heading h2').innerText(),'部署服务容器发现');
    await inventoryToggle.press('Space');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.textContent),'容器服务');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.textContent),'部署服务容器发现');
    await page.locator('.ant-pagination-next button').click();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).waitFor({state:'hidden'});
    const saved = page.waitForResponse(r => r.url().includes('/api/v1/baseline/selection') && r.request().method()==='POST' && r.ok());
    await page.getByRole('button', {name:'保存并生效',exact:true}).click();
    const baseline = await (await saved).json();
    assert.equal(baseline.definition.clusters.flatMap(c=>c.services.flatMap(s=>s.nodes)).length,1);
    await containerLoading.list(page);
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).waitFor();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('button',{name:'设置',exact:true}).click();
    await page.getByLabel('TCP 端口与业务探测',{exact:true}).fill('8000, 8001');
    const checks = page.waitForResponse(r => r.url().includes('/api/v1/baseline/checks') && r.request().method()==='POST' && r.ok());
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    const configured=await (await checks).json();
    assert.deepEqual(configured.definition.clusters[0].services[0].nodes[0].checks.map(c=>c.port),[8000,8001]);
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('button',{name:'设置',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'移出台账',exact:true}).click();
    await page.getByText('待保存移出',{exact:true}).waitFor();
    await page.getByRole('button',{name:'取消移出 agora_local_ap',exact:true}).click();
    assert.equal(await page.getByText('待保存移出',{exact:true}).count(),0);
    await openPage(page, '监控', '容器服务');
    await containerLoading.detail(page, requests);
    await openPage(page, '通知投递', '投递记录');
    await openPage(page, '通知投递', '接收配置');
    await checkCurrent(page, '接收配置');
    assert.equal(new URL(page.url()).pathname,'/notifications/config');
    await page.reload(); await checkCurrent(page, '接收配置');
    await page.goBack(); await page.locator('.workspace-page-heading').getByRole('heading',{name:'投递记录',exact:true}).waitFor();
    await page.goForward(); await page.locator('.workspace-page-heading').getByRole('heading',{name:'接收配置',exact:true}).waitFor();
    await openPage(page, '管理', '账号管理');
    assert.equal(await page.getByRole('link',{name:'角色说明',exact:true}).count(),0);
    await page.getByText('查看监控、配置通知及受控重启。',{exact:false}).waitFor();
    await openPage(page, '运维', '中心容量');
    await page.getByText('开发存储不提供数据库容量统计').waitFor();
    await openPage(page, '监控', '容器服务');
    await page.getByRole('button',{name:'查看详情',exact:true}).click();
    for (const width of [1024,768,390,320]) {
      await page.setViewportSize({width,height:844});
      await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth+1, null, {timeout:5000}).catch(()=>{});
      const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
      if (overflow) {
        await page.screenshot({path:'/tmp/monitor-workbench-overflow.png',fullPage:true});
        console.log(await page.evaluate(()=>[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1&&getComputedStyle(e).overflowX==='visible').map(e=>({tag:e.tagName,cls:String(e.className),width:e.getBoundingClientRect().width,right:e.getBoundingClientRect().right})).slice(0,12)));
      }
      assert.ok(!overflow, `overflow at ${width}px`);
    }
    await page.getByRole('button',{name:'关闭容器详情',exact:true}).click();
    await page.getByRole('dialog',{name:'容器详情',exact:true}).waitFor({state:'hidden'});
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('navigation',{name:'工作台导航'}).waitFor({state:'hidden'});
    await page.locator('.workspace-mobile-nav-toggle').focus();
    await page.locator('.workspace-mobile-nav-toggle').press('Enter');
    await page.getByRole('navigation',{name:'工作台导航'}).waitFor({state:'visible'});
    await openPage(page,'通知投递','投递记录');
    await page.getByRole('navigation',{name:'工作台导航'}).waitFor({state:'hidden'});
    assert.ok(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1));
    const customer = await browser.newPage();
    const customerRequests = [];
    customer.on('pageerror', e => errors.push(e.message));
    customer.on('request', r => customerRequests.push(new URL(r.url()).pathname));
    await customer.addInitScript(()=>localStorage.setItem('avops-monitor-authorization','Bearer ui-fixture-token'));
    await customer.route('**/version', async route => {
      const response = await route.fetch(), version = await response.json();
      version.can_manage_keys = false;
      version.permissions = ['monitor.read','notifications.write','restart.execute','restart.result'];
      version.user.role_ids = ['customer_ops'];
      await route.fulfill({response,json:version});
    });
    await customer.goto(new URL('/?view=accounts&page=roles',url).toString());
    await customer.locator('.workspace-page-heading').getByRole('heading',{name:'运行总览',exact:true}).waitFor();
    assert.equal(new URL(customer.url()).pathname,'/overview');
    const customerNav = customer.getByRole('navigation',{name:'工作台导航'});
    assert.equal(await customerNav.getByRole('button',{name:'管理',exact:true}).count(),0);
    assert.equal(await customerNav.getByRole('link',{name:'部署服务容器发现',exact:true}).count(),0);
    await openPage(customer,'运维','我的重启');
    assert.equal(await customerNav.getByRole('link',{name:'中心容量',exact:true}).count(),1);
    await openSection(customer,'部署服务可用性探测');
    await customerNav.getByRole('link',{name:'探测点任务配置',exact:true}).click();
    await customer.getByRole('heading',{name:'部署服务可用性探测',exact:true}).waitFor();
    assert.equal(await customer.getByRole('button',{name:'创建探测点任务',exact:true}).count(),0);
    assert.ok(!customerRequests.includes('/api/v1/users') && !customerRequests.includes('/api/v1/baseline') && !customerRequests.includes('/api/v1/storage/status'));
    const failing = await browser.newPage();
    await failing.addInitScript(()=>localStorage.setItem('avops-monitor-authorization','Bearer ui-fixture-token'));
    await failing.route('**/api/v1/services/status**',r=>r.fulfill({status:503,json:{message:'隔离测试：读取失败'}}));
    await failing.goto(new URL('/?view=status',url).toString());
    await failing.getByText('尚未读到有效数据，请重试。',{exact:true}).waitFor();
    assert.equal(await failing.getByRole('table').count(),0);
    await failing.unroute('**/api/v1/services/status**');
    await failing.getByRole('button',{name:'重试',exact:true}).click();
    await failing.getByRole('table').waitFor();
    assert.deepEqual(errors,[]);
    console.log('PASS: account login, scoped queries, cross-page draft/save, node settings, startup, charts, navigation keyboard, URL restore/back/forward, separated modules, customer permission guards, failed-read retry and responsive layout');
  } catch (e) {
    console.error('UI failure', page.url(), await page.locator('h2').allTextContents());
    require('node:fs').writeFileSync('/tmp/avops-container-loading-failure.html', await page.content());
    throw e;
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
