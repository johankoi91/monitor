// Isolated fixture only: exercises Agent packing and browser download together.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { chromium } = require(process.env.AVOPS_PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  assert.equal(process.env.AVOPS_ISOLATED_UI_TEST, '1');
  const url = new URL(process.env.AVOPS_UI_URL);
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname));
  const browser = await chromium.launch({ headless: true, executablePath: process.env.AVOPS_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, timezoneId: 'UTC', acceptDownloads: true });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(new URL('/monitor/logs', url).toString());
    await page.getByLabel('账号', { exact: true }).fill('fixture');
    await page.getByLabel('密码', { exact: true }).fill('fixture123');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('heading', { name: '日志拉取', exact: true }).waitFor();
    const navigation = page.getByRole('navigation', { name: '工作台导航' });
    assert.equal(await navigation.getByRole('link', { name: '日志拉取', exact: true }).getAttribute('aria-current'), 'page');
    const panel = page.locator('.log-collection-page');
    await panel.getByText('日志来源与匹配说明', { exact: true }).click();
    await panel.getByText('/custom/agora', { exact: true }).waitFor();
    await panel.getByText('日志来源与匹配说明', { exact: true }).click();
    const qa = process.env.AVOPS_QA_OUTPUT || '/tmp/avops-log-collection-qa'; fs.mkdirSync(qa, { recursive: true });
    await page.screenshot({ path: path.join(qa, 'redesign-idle.png'), fullPage: true });
    assert.equal(await panel.getByRole('button', { name: '开始拉取', exact: true }).isDisabled(), true, 'empty container selection must not collect the whole host');
    const services = panel.locator('#log-service');
    await services.click();
    const picker = page.getByRole('dialog', { name: '选择服务容器', exact: true });
    await picker.getByRole('checkbox', { name: '其他服务', exact: true }).check();
    await picker.getByRole('button', { name: '取消', exact: true }).click();
    assert.equal(await services.innerText(), '选择服务容器', 'cancel applied a draft selection');
    await services.click();
    await picker.getByRole('textbox', { name: '搜索服务容器', exact: true }).fill('no-match');
    await picker.getByText('没有匹配的容器，试试其他名称', { exact: true }).waitFor();
    await picker.getByRole('textbox', { name: '搜索服务容器', exact: true }).fill('media');
    await picker.getByRole('checkbox', { name: '全选当前结果', exact: true }).check();
    assert.equal(await picker.getByRole('checkbox', { name: 'unavailable-service', exact: true }).count(), 0, 'unavailable service was shown');
    assert.equal(await picker.locator('.ant-checkbox-wrapper-disabled').count(), 0, 'disabled choices were shown');
    await picker.getByRole('checkbox', { name: '只看已选', exact: true }).check();
    await picker.getByRole('button', { name: '确认选择', exact: true }).click({ trial: true });
    await page.screenshot({ path: path.join(qa, 'picker.png'), fullPage: true });
    await picker.getByRole('button', { name: '确认选择', exact: true }).click();
    await panel.getByText('日志来源与匹配说明', { exact: true }).click();
    await panel.getByText(/media_edge_1 · PID 123/).waitFor();
    await panel.getByText(/media_edge_1 · PID 124/).waitFor();
    await panel.getByText('日志来源与匹配说明', { exact: true }).click();
    await panel.getByLabel('目标时间', { exact: true }).fill('2026-05-22T03:45');
    const created = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/log-collections' && r.request().method() === 'POST' && r.ok());
    await panel.getByRole('button', { name: '开始拉取', exact: true }).click();
    const createdResponse = await created;
    const body = createdResponse.request().postDataJSON();
    assert.equal(body.agent_id, 'fixture');
    assert.deepEqual(body.service_container_ids, ['media-id', 'media2-id']);
    assert.ok(!Object.hasOwn(body, 'node_id'), 'collection was bound to a container');
    assert.equal(body.time, '2026-05-22T03:45:00.000Z');
    const job = await createdResponse.json();
    await page.reload();
    await page.getByRole('heading', { name: '日志拉取', exact: true }).waitFor();
    await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).waitFor();
    assert.deepEqual(await panel.locator('.log-selected-tag > span').allTextContents(), ['media', 'media2']);
    const restored = await page.evaluate(id => Object.values(sessionStorage).includes(id), job.id);
    assert.ok(restored, 'collection did not survive refreshing the page');
    const downloadEvent = page.waitForEvent('download');
    await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).click();
    const download = await downloadEvent;
    assert.equal(download.suggestedFilename(), 'agora_logs_20260522T034500Z_fixture_2-services.tar.gz');
    assert.equal(await download.failure(), null);
    const tar = zlib.gunzipSync(fs.readFileSync(await download.path()));
    assert.ok(tar.includes(Buffer.from('log content from the Agent host filesystem')));
    assert.ok(tar.includes(Buffer.from('log from second selected container')));
    assert.ok(!tar.includes(Buffer.from('LOG_FROM_OTHER_CONTAINER_MUST_BE_EXCLUDED')));
    await page.getByText('压缩包信息', { exact: true }).click();
    await panel.getByText(download.suggestedFilename(), { exact: true }).waitFor();
    await page.getByText('压缩包信息', { exact: true }).click();
    await page.route('**/api/v1/log-collections/' + job.id, async route => {
      const response = await route.fetch();
      const value = await response.json();
      await route.fulfill({ response, json: { ...value, expires_at: '2000-01-01T00:00:00Z' } });
    });
    await page.reload();
    await panel.getByText('日志包已过期', { exact: true }).waitFor();
    assert.equal(await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).count(), 0);
    assert.equal(await panel.getByRole('button', { name: '开始拉取', exact: true }).isEnabled(), true);
    await page.unroute('**/api/v1/log-collections/' + job.id);
    await page.reload();
    await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).waitFor();
    const output = qa;
    fs.mkdirSync(output, { recursive: true });
    await panel.getByRole('button', { name: '开始拉取', exact: true }).click({ trial: true });
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    // Removing a tag keeps the remaining container as an explicit filter.
    await panel.getByRole('button', { name: '移除 media2', exact: true }).click();
    const singleRequest = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/log-collections' && r.request().method() === 'POST' && r.ok());
    await panel.getByRole('button', { name: '开始拉取', exact: true }).click();
    assert.deepEqual((await singleRequest).request().postDataJSON().service_container_ids, ['media-id']);
    await panel.getByText('日志包已就绪', { exact: true }).waitFor();
    const singleDownloadEvent = page.waitForEvent('download');
    await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).click();
    const singleDownload = await singleDownloadEvent;
    assert.equal(singleDownload.suggestedFilename(), 'agora_logs_20260522T034500Z_fixture_media.tar.gz');
    const singleTar = zlib.gunzipSync(fs.readFileSync(await singleDownload.path()));
    assert.ok(!singleTar.includes(Buffer.from('log from second selected container')));
    // Removing the last container cannot silently widen the request to a host.
    await panel.getByRole('button', { name: '移除 media', exact: true }).click();
    assert.equal(await panel.getByRole('button', { name: '开始拉取', exact: true }).isDisabled(), true);
    await panel.getByText('整台机器', { exact: true }).click();
    const allRequest = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/log-collections' && r.request().method() === 'POST' && r.ok());
    await panel.getByRole('button', { name: '开始拉取', exact: true }).click();
    assert.deepEqual((await allRequest).request().postDataJSON().service_container_ids, []);
    await panel.getByText('日志包已就绪', { exact: true }).waitFor();
    await panel.getByLabel('主机 IP', { exact: true }).fill('127.0.0.2');
    await page.getByTitle('127.0.0.2', { exact: true }).click();
    await panel.getByText('Agent 离线或采样已过期，暂不能拉取日志', { exact: true }).waitFor();
    assert.equal(await panel.getByRole('button', { name: '开始拉取', exact: true }).isDisabled(), true);
    assert.equal(await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).count(), 0);
    await panel.getByLabel('主机 IP', { exact: true }).fill('127.0.0.1');
    await page.getByTitle('127.0.0.1', { exact: true }).click();
    await panel.getByRole('button', { name: '下载日志压缩包', exact: true }).waitFor();
    await panel.getByText('UTC 全天', { exact: true }).click();
    await panel.getByLabel('UTC 日期', { exact: true }).fill('2026-05-23');
    const dayRequest = page.waitForResponse(r => new URL(r.url()).pathname === '/api/v1/log-collections' && r.request().method() === 'POST' && r.ok());
    await panel.getByRole('button', { name: '开始拉取', exact: true }).click();
    const dayBody = (await dayRequest).request().postDataJSON();
    assert.equal(dayBody.time, '20260523');
    assert.equal(dayBody.mode, 'day');
    await panel.getByText('未找到时间窗口内对应的日志文件', { exact: true }).waitFor();
    await page.setViewportSize({ width: 375, height: 812 });
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'horizontal page overflow');
    await panel.getByText('指定容器', { exact: true }).click();
    await services.click();
    await picker.getByRole('checkbox', { name: '其他服务', exact: true }).check();
    await picker.getByRole('button', { name: '确认选择', exact: true }).click({ trial: true });
    await page.screenshot({ path: path.join(output, 'mobile-picker.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile picker overflow');
    await picker.getByRole('textbox', { name: '搜索服务容器', exact: true }).press('Escape');
    await picker.waitFor({ state: 'hidden' });
    await services.click({ trial: true });
    await page.setViewportSize({ width: 768, height: 1024 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'tablet overflow');
    await page.setViewportSize({ width: 812, height: 375 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'landscape overflow');
    await services.click();
    await picker.getByRole('button', { name: '取消', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('Verified multi-container packing, hidden unavailable choices, restored selections, single and whole-host modes, downloaded contents, UTC day, empty-window feedback and responsive layout.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
