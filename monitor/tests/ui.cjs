// Runs only against the isolated Go browser fixture, never a business host.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.AVOPS_PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  assert.equal(process.env.AVOPS_ISOLATED_UI_TEST, '1');
  const url = new URL(process.env.AVOPS_UI_URL);
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname));
  const browser = await chromium.launch({ headless: true, executablePath: process.env.AVOPS_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => requests.push(new URL(r.url()).pathname));
    await page.goto(url.toString());
    await page.getByLabel('账号', {exact:true}).fill('fixture');
    await page.getByLabel('密码', {exact:true}).fill('fixture123');
    await page.getByRole('button', {name:'登录',exact:true}).click();
    await page.getByRole('heading', {name:'服务状态',exact:true}).waitFor();
    assert.ok(!requests.includes('/api/v1/containers') && !requests.includes('/api/v1/notifications/status'));
    await page.getByRole('tab', {name:'容器与基准台账',exact:true}).click();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('checkbox').check();
    await page.getByLabel('分组名', {exact:true}).fill('回归验证组');
    await page.getByRole('button', {name:'加入待保存变更',exact:true}).click();
    await page.locator('.ant-pagination-next button').click();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).waitFor({state:'hidden'});
    const saved = page.waitForResponse(r => r.url().includes('/api/v1/baseline/selection') && r.request().method()==='POST' && r.ok());
    await page.getByRole('button', {name:'保存并生效',exact:true}).click();
    const baseline = await (await saved).json();
    assert.equal(baseline.definition.clusters.flatMap(c=>c.services.flatMap(s=>s.nodes)).length,1);
    await page.getByRole('tab', {name:/当前基准/}).click();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).waitFor();
    await page.getByRole('row').filter({hasText:'agora_local_ap'}).getByRole('button',{name:'设置',exact:true}).click();
    await page.getByLabel('TCP 端口与业务探测',{exact:true}).fill('8000, 8001');
    const checks = page.waitForResponse(r => r.url().includes('/api/v1/baseline/checks') && r.request().method()==='POST' && r.ok());
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    const configured=await (await checks).json();
    assert.deepEqual(configured.definition.clusters[0].services[0].nodes[0].checks.map(c=>c.port),[8000,8001]);
    await page.getByRole('tab',{name:'服务状态',exact:true}).click();
    await page.getByRole('button',{name:'查看 agora_local_ap 详情',exact:true}).click();
    await page.getByRole('tab',{name:'启动参数',exact:true}).click();
    await page.getByText(/最新上报/).waitFor();
    assert.equal(await page.locator('.startup-toolbar button').count(),0);
    assert.ok(!requests.includes('/api/v1/nodes/startup'));
    await page.getByRole('tab',{name:'资源详情',exact:true}).click();
    await page.locator('.resource-trend-canvas canvas').first().waitFor();
    assert.equal(await page.locator('.resource-trend-canvas canvas').count(),4);
    await page.getByRole('button',{name:'精确数据表',exact:true}).press('Enter');
    await page.getByRole('region',{name:'资源趋势精确数据表',exact:true}).waitFor();
    assert.ok(new URL(page.url()).searchParams.get('node'));
    await page.getByRole('tab',{name:'操作与审计',exact:true}).click();
    await page.goBack();
    await page.getByRole('region',{name:'资源趋势精确数据表',exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.ok(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1));
    assert.deepEqual(errors,[]);
    console.log('PASS: account login, scoped queries, cross-page selection/save, node settings, reported startup, four charts and mobile layout');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e.message);process.exitCode=1});
